    func testEditingAnExistingCyclesLengthAssumptionsChangesItsWindow() throws {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(secondsFromGMT: 0)!
        let start = try XCTUnwrap(calendar.date(from: DateComponents(year: 2026, month: 8, day: 3)))
        let cycle = CycleRecord(startDate: start, averageCycleLengthAtStart: 28, lutealPhaseLengthAtStart: 14)

        let before = try XCTUnwrap(CycleTrackingService.window(records: [cycle], settings: nil, calendar: calendar))

        // Mirrors what CycleRecordEditor.save() does when the user edits this
        // specific cycle's length assumptions after the fact, rather than
        // only being able to change the global default for future cycles.
        cycle.averageCycleLengthAtStart = 32
        cycle.lutealPhaseLengthAtStart = 12

        let after = try XCTUnwrap(CycleTrackingService.window(records: [cycle], settings: nil, calendar: calendar))

        XCTAssertNotEqual(before.predictedOvulationDate, after.predictedOvulationDate)
        XCTAssertNotEqual(before.nextPeriodDate, after.nextPeriodDate)
    }

