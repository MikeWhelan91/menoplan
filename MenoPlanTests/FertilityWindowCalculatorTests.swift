    func testIrregularCyclesWidenTheTestingWindow() throws {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(secondsFromGMT: 0)!
        let start = try XCTUnwrap(calendar.date(from: DateComponents(year: 2026, month: 5, day: 1)))
        let today = try XCTUnwrap(calendar.date(from: DateComponents(year: 2026, month: 5, day: 10)))

        let steady = try XCTUnwrap(FertilityWindowCalculator.window(for: today, lastPeriodStart: start, averageCycleLength: 28, lutealPhaseLength: 14, calendar: calendar))
        XCTAssertFalse(steady.isIrregular)

        let irregular = try XCTUnwrap(FertilityWindowCalculator.window(for: today, lastPeriodStart: start, averageCycleLength: 28, lutealPhaseLength: 14, cycleLengthVariabilityDays: 10, calendar: calendar))
        XCTAssertTrue(irregular.isIrregular)
        // Widened by min(5, 10/2) = 5 days, but the early side stops at the
        // day after the period (cycle day 6 with a 5-day period) so it never
        // contradicts the period days drawn on the calendar.
        let dayAfterPeriod = try XCTUnwrap(calendar.date(from: DateComponents(year: 2026, month: 5, day: 6)))
        XCTAssertEqual(irregular.fertileStartDate, dayAfterPeriod)
        XCTAssertEqual(calendar.dateComponents([.day], from: steady.fertileEndDate, to: irregular.fertileEndDate).day, 5)
        XCTAssertEqual(irregular.opkStartDate, dayAfterPeriod)
        XCTAssertLessThan(irregular.fertileStartDate, steady.fertileStartDate)
        // Ovulation/period dates themselves are estimates of a single day and
        // stay put - only the start of the testing window moves earlier.
        XCTAssertEqual(irregular.predictedOvulationDate, steady.predictedOvulationDate)
        XCTAssertEqual(irregular.nextPeriodDate, steady.nextPeriodDate)
    }

