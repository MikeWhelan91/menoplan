private struct PeriodEventEditor: View {
    @Environment(\.dismiss) private var dismiss
    @Environment(\.modelContext) private var modelContext
    @Query(sort: \CycleRecord.startDate) private var cycles: [CycleRecord]
    @Query(sort: \PeriodEvent.startDate) private var periods: [PeriodEvent]
    @Query(sort: \Reminder.scheduledDate) private var reminders: [Reminder]
    @Query private var settingsQuery: [UserSettings]
    let period: PeriodEvent
    @State private var startDate: Date
    @State private var hasEndDate: Bool
    @State private var endDate: Date

    init(period: PeriodEvent) {
        self.period = period
        _startDate = State(initialValue: period.startDate)
        _hasEndDate = State(initialValue: period.endDate != nil)
        _endDate = State(initialValue: period.endDate ?? Calendar.current.date(byAdding: .day, value: 4, to: period.startDate) ?? period.startDate)
    }

    // Moving this period's dates onto another logged period's range would
    // produce two overlapping periods with no clear "current" one - block it
    // rather than silently corrupting the cycle history.
    private var overlapError: String? {
        let calendar = Calendar.current
        let newStart = calendar.startOfDay(for: startDate)
        let newEnd = calendar.startOfDay(for: hasEndDate ? endDate : (calendar.date(byAdding: .day, value: 4, to: newStart) ?? newStart))
        for other in periods where other.id != period.id && !other.notes.contains("[LineCheck Screenshot Sample]") {
            let otherStart = calendar.startOfDay(for: other.startDate)
            let otherEnd = calendar.startOfDay(for: other.endDate ?? calendar.date(byAdding: .day, value: 4, to: otherStart) ?? otherStart)
            if newStart <= otherEnd && otherStart <= newEnd {
                return "That overlaps with the period logged on \(DateFormatting.shortDate.string(from: otherStart))."
            }
        }
        return nil
    }

    var body: some View {
        NavigationStack {
            Form {
                DatePicker("Period started", selection: $startDate, in: earliestReasonableCycleDate...Date.now, displayedComponents: .date)
                Toggle("Period end is known", isOn: $hasEndDate)
                if hasEndDate {
                    DatePicker("Period ended", selection: $endDate, in: startDate..., displayedComponents: .date)
                }
                Text("If you leave the end date unknown, MenoPlan displays an estimated five-day period without treating that duration as confirmed data.")
                    .font(.app(.caption))
                    .foregroundStyle(.secondary)
                if let overlapError {
                    Text(overlapError)
                        .font(.app(.caption))
                        .foregroundStyle(.red)
                }
                Button("Save Period") { save() }
                    .buttonStyle(.primaryLine)
                    .disabled(overlapError != nil)
            }
            .navigationTitle("Edit Period")
            .toolbar { ToolbarItem(placement: .cancellationAction) { Button("Cancel") { dismiss() } } }
        }
        .tint(Color.lineBlue)
    }

    private func save() {
        guard overlapError == nil else { return }
        let calendar = Calendar.current
        let oldStart = period.startDate
        let startDateChanged = !calendar.isDate(oldStart, inSameDayAs: startDate)
        period.startDate = calendar.startOfDay(for: startDate)
        period.endDate = hasEndDate ? calendar.startOfDay(for: endDate) : nil
        var resyncCycle: CycleRecord?
        if let cycle = cycles.first(where: { $0.id == period.cycleRecordID || calendar.isDate($0.startDate, inSameDayAs: oldStart) }) {
            cycle.startDate = period.startDate
            if cycle.confirmedOvulationDate == nil {
                let base = FertilityWindowCalculator.window(lastPeriodStart: cycle.startDate, averageCycleLength: cycle.averageCycleLengthAtStart, lutealPhaseLength: cycle.lutealPhaseLengthAtStart)
                if cycle.ovulationSource == nil { cycle.predictedOvulationDate = base?.predictedOvulationDate }
                cycle.expectedPeriodDate = base?.nextPeriodDate
            }
            resyncCycle = cycle
        }
        let sorted = cycles.filter { !$0.notes.contains("[LineCheck Screenshot Sample]") }.sorted { $0.startDate < $1.startDate }
        for (index, cycle) in sorted.enumerated() {
            cycle.endDate = index + 1 < sorted.count ? sorted[index + 1].startDate : nil
            // Don't clobber a status this cycle earned for a reason unrelated to
            // chronological order (e.g. .archived for a pregnancy-confirmed
            // cycle, set in CycleTrackingService.recordPeriodStart) - only ever
            // toggle between the two ordering-derived states.
            if cycle.status == .active || cycle.status == .completed {
                cycle.status = index + 1 < sorted.count ? .completed : .active
            }
        }
        var settingsForResync: UserSettings?
        if let settings = UserSettings.canonical(from: settingsQuery) {
            let realPeriods = periods.filter { !$0.notes.contains("[LineCheck Screenshot Sample]") }
            settings.lastPeriodStartDate = realPeriods.map(\.startDate).max()
            settings.averageCycleLength = CycleTrackingService.learnedAverageCycleLength(from: realPeriods, fallback: settings.averageCycleLength)
            settingsForResync = settings
        }
        try? modelContext.save()
        // A moved start date shifts fertile-window/ovulation/period-expected
        // timing, so any auto-generated reminders need to be rescheduled
        // rather than left firing on the old dates.
        if startDateChanged, let cycle = resyncCycle, let settings = settingsForResync,
           let window = CycleTrackingService.window(records: cycles, periods: periods, settings: settings) {
            Task { await ReminderAutomationService.syncPredictedReminders(cycle: cycle, window: window, settings: settings, existingReminders: reminders, context: modelContext) }
        }
        dismiss()
    }
}

