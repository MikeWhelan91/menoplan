        return DGLineChart(points: points, color: LineCheckChartColor.purple, yFormatter: { "\($0.formatted(.number.precision(.fractionLength(1))))\(unit.title)" }, verticalMarkers: markers, horizontalMarkers: coverlineMarker(), isZoomable: true)
    }

    /// The average of the pre-ovulation (follicular) readings this cycle -
    /// the reference point every bar on the deviation chart is measured
    /// against, mirroring how BBT is conventionally read (a rise relative
    /// to your own recent normal, not an absolute number that varies a lot
    /// between people).
    private func bbtBaselineCelsius(logs: [DailyFertilityLog], window: FertilityWindow) -> Double? {
        let ovulationDay = Calendar.current.startOfDay(for: window.predictedOvulationDate)
        let preOvulation = logs.filter { Calendar.current.startOfDay(for: $0.date) >= Calendar.current.startOfDay(for: window.cycleStart) && Calendar.current.startOfDay(for: $0.date) < ovulationDay }.compactMap(\.basalBodyTemperatureCelsius)
        guard preOvulation.count >= 3 else { return nil }
        return preOvulation.reduce(0, +) / Double(preOvulation.count)
    }

    /// A rise in temperature after ovulation (progesterone's thermogenic
    /// effect) is the classic BBT confirmation pattern - describe whether
    /// this user's own logged data actually shows it, rather than a static
    /// caption that never reflects what's on screen.
    private func bbtNarrative(logs: [DailyFertilityLog]) -> String? {
        guard let window = chartRelevantFertilityWindow, logs.count >= 4 else { return nil }
        let ovulationDay = Calendar.current.startOfDay(for: window.predictedOvulationDate)
        let before = logs.filter { Calendar.current.startOfDay(for: $0.date) < ovulationDay }.compactMap(\.basalBodyTemperatureCelsius)
        let after = logs.filter { Calendar.current.startOfDay(for: $0.date) >= ovulationDay }.compactMap(\.basalBodyTemperatureCelsius)
        guard before.count >= 2, after.count >= 2 else { return nil }
        let beforeAvg = before.reduce(0, +) / Double(before.count)
        let afterAvg = after.reduce(0, +) / Double(after.count)
        let unit = settings?.temperatureUnit ?? .localeDefault
        let deltaCelsius = afterAvg - beforeAvg
        let displayDelta = unit == .fahrenheit ? deltaCelsius * 9 / 5 : deltaCelsius
        let formattedDelta = abs(displayDelta).formatted(.number.precision(.fractionLength(1)))
        if deltaCelsius >= 0.15 {
            return "Your average temperature rose \(formattedDelta)\(unit.title) after your estimated ovulation day, consistent with a post-ovulation shift."
        } else if deltaCelsius <= -0.1 {
            return "Your average temperature is lower after your estimated ovulation day than before it - not the rise usually seen after ovulation, so treat this cycle's estimate with a little more caution."
        } else {
            return "No clear temperature shift yet around your estimated ovulation day - a shift can also show up a day or two later than predicted."
        }
    }

    private func bbtDeviationChart(logs: [DailyFertilityLog], window: FertilityWindow, baselineCelsius: Double) -> DGBarChart {
        let unit = settings?.temperatureUnit ?? .localeDefault
        let ovulationDay = Calendar.current.startOfDay(for: window.predictedOvulationDate)
        let points = logs.enumerated().map { index, log -> ChartPoint in
            let raw = log.basalBodyTemperatureCelsius ?? baselineCelsius
            let deviationCelsius = raw - baselineCelsius
            let displayDeviation = unit == .fahrenheit ? deviationCelsius * 9 / 5 : deviationCelsius
            let isPostOvulation = Calendar.current.startOfDay(for: log.date) >= ovulationDay
            let sign = displayDeviation >= 0 ? "+" : ""
            return ChartPoint(
                x: Double(index),
                y: displayDeviation,
                label: DateFormatting.axisDate.string(from: log.date),
                markerColor: UIColor(isPostOvulation ? Color.linePurple : Color.lineNavy.opacity(0.32)),
                markerText: "\(DateFormatting.shortDate.string(from: log.date))\n\(sign)\(displayDeviation.formatted(.number.precision(.fractionLength(2))))\(unit.title) vs baseline"
            )
        }
        let markers = bbtChartVerticalMarkers(logDates: logs.map { Calendar.current.startOfDay(for: $0.date) })
        return DGBarChart(
            points: points,
            color: LineCheckChartColor.purple,
            yAxisMin: nil,
            yFormatter: { value in "\(value >= 0 ? "+" : "")\(value.formatted(.number.precision(.fractionLength(1...2))))\(unit.title)" },
            zeroLine: true,
            verticalMarkers: markers,
            horizontalMarkers: coverlineMarker(offsetBy: baselineCelsius),
            isZoomable: true
        )
    }

    /// A single at-a-glance line for today specifically - "N DPO, +delta vs
    /// your own baseline" - rather than making the reader interpret the
    /// whole chart themselves to answer "where am I right now".
    private func bbtTodayInsight(logs: [DailyFertilityLog], window: FertilityWindow, baselineCelsius: Double) -> (title: String, detail: String)? {
        guard let latest = logs.last, let latestTemp = latest.basalBodyTemperatureCelsius else { return nil }
        let calendar = Calendar.current
        let cycleStartDay = calendar.startOfDay(for: window.cycleStart)
        let ovulationDay = calendar.startOfDay(for: window.predictedOvulationDate)
        let latestDay = calendar.startOfDay(for: latest.date)
        // The most recent logged day predating this window's own cycle start
        // means the log doesn't actually belong to the cycle being shown
        // (e.g. a date-range filter surfacing an older log while "cycle
        // start" is anchored to a different, newer cycle) - a "cycle day 0"
        // or negative count would be nonsensical, so skip the insight rather
        // than show a confusing number.
        guard latestDay >= cycleStartDay else { return nil }
        let dpo = calendar.dateComponents([.day], from: ovulationDay, to: latestDay).day ?? 0
        let unit = settings?.temperatureUnit ?? .localeDefault
        let deltaCelsius = latestTemp - baselineCelsius
        let displayDelta = unit == .fahrenheit ? deltaCelsius * 9 / 5 : deltaCelsius
        let sign = displayDelta >= 0 ? "+" : ""
        let formattedDelta = "\(sign)\(displayDelta.formatted(.number.precision(.fractionLength(2))))\(unit.title)"

        let title: String
        let detail: String
        if latestDay < ovulationDay {
            let cycleDay = (calendar.dateComponents([.day], from: cycleStartDay, to: latestDay).day ?? 0) + 1
            title = "Cycle day \(max(1, cycleDay)) - pre-ovulation check"
            detail = "\(formattedDelta) vs baseline. Temperatures are typically flat or low until ovulation."
        } else if dpo == 0 {
            title = "Ovulation day check"
            detail = "\(formattedDelta) vs baseline. A clear rise often shows up over the next 1-3 days."
        } else {
            title = "\(dpo) DPO - luteal pattern check"
            detail = deltaCelsius >= 0.15
                ? "\(formattedDelta) vs baseline. Continued elevation is common after ovulation."
                : "\(formattedDelta) vs baseline. Less elevated than a typical post-ovulation pattern so far."
        }
        return (title, detail)
    }

    private func bbtTrend(logs: [DailyFertilityLog]) -> String? {
        let values = logs.compactMap(\.basalBodyTemperatureCelsius)
        guard values.count >= 4 else { return nil }
        let recentCount = min(3, values.count / 2)
        let recent = values.suffix(recentCount)
        let earlier = values.dropLast(recentCount).suffix(recentCount)
        guard !earlier.isEmpty else { return nil }
        let recentAvg = recent.reduce(0, +) / Double(recent.count)
        let earlierAvg = earlier.reduce(0, +) / Double(earlier.count)
        let delta = recentAvg - earlierAvg
        if delta >= 0.08 { return "Rising" }
        if delta <= -0.08 { return "Falling" }
        return "Steady"
    }

