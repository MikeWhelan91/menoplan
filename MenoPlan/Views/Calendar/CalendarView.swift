    /// The structured facts a doctor visit actually starts with - LMP, cycle length,
    /// predicted ovulation, recent notable test dates - pulled straight from existing
    /// records rather than read off a chart. Drawn as the report's cover section, ahead of
    /// the chart images.
    private func reportSummaryLines(scope: TrendsExportScope) -> [(label: String, value: String)] {
        var lines: [(label: String, value: String)] = []
        if let lmp = calendarPeriodEvents.map(\.startDate).max() {
            lines.append(("Last period started", DateFormatting.shortDate.string(from: lmp)))
        }
        if let settings {
            lines.append(("Average cycle length", "\(settings.averageCycleLength) days"))
        }
        if let period = CycleTrendsCalculator.averagePeriodLength(calendarPeriodEvents) {
            lines.append(("Average period length", "\(period) days"))
        }
        let history = cycleHistory
        if let accuracy = CycleTrendsCalculator.accuracySummary(history) {
            lines.append(("Period forecast accuracy", "\(accuracy.withinOneDay) of \(accuracy.count) within 1 day"))
        }
        if let window = fertilityWindow {
            lines.append(("Current cycle day", "Day \(window.cycleDay)"))
            lines.append(("Next expected period", DateFormatting.shortDate.string(from: window.nextPeriodDate)))
        }
        do {
            let peaks = scans
                .filter { $0.testType == .ovulation && ($0.resultType == .peak || $0.resultType == .high) }
                .sorted { $0.createdAt > $1.createdAt }
                .prefix(3)
            if !peaks.isEmpty {
                lines.append(("Recent high test readings", peaks.map { DateFormatting.shortDate.string(from: $0.createdAt) }.joined(separator: ", ")))
            }
        }
        return lines
    }

    /// DGCharts draws via Core Graphics rather than pure SwiftUI, so
    /// SwiftUI's ImageRenderer produces a "content unavailable" placeholder
    /// for a live chart view instead of the real drawing - each chart is
    /// rasterized through DGLineChart/DGBarChart's own renderedImage(size:)
    /// instead, which uses DGCharts' native export path. Plain SwiftUI
    /// content (the symptom/mood summaries) doesn't have that problem and
    /// still goes through ImageRenderer.
    private func captionHeight(_ text: String, width: CGFloat, font: UIFont) -> CGFloat {
        let bounding = (text as NSString).boundingRect(
            with: CGSize(width: width, height: .greatestFiniteMagnitude),
            options: [.usesLineFragmentOrigin, .usesFontLeading],
            attributes: [.font: font],
            context: nil
        )
        return ceil(bounding.height)
    }

    @MainActor
    private func renderTrendsPDF(scope: TrendsExportScope) -> URL? {
        let chartSize = CGSize(width: 1160, height: 520)
        var sections: [(title: String, tint: Color, image: UIImage, caption: String?)] = []

        // isZoomable charts only show a recent windowed slice on screen (the
        // rest is reachable by panning) - a static export can't pan, so it
        // must show the complete range at once instead of reproducing
        // whatever narrow window happened to be on screen. Each chart's
        // on-screen narrative caption is carried into the report too - a
        // doctor visit report of unlabeled chart images with no context is
        // far less useful than what the app itself already tells the user.
        do {
            if var chart = ovulationTrendChart() {
                chart.isZoomable = false
                if let image = chart.renderedImage(size: chartSize) {
                    let caption = ProgressionNarrativeBuilder.ovulationNarrative(scans: ovulationProgressionScans)
                    sections.append(("Test Trend", .linePurple, image, caption))
                }
            }
        }
        let history = filteredCycleHistory
        if !history.isEmpty, let image = snapshotPlainView(CycleHistoryChart(entries: history, limit: 12), width: chartSize.width / 2) {
            sections.append(("Cycle History", .linePink, image, nil))
        }
        if CycleTrendsCalculator.accuracySummary(history) != nil, let image = snapshotPlainView(PredictionAccuracyChart(entries: history).frame(height: 280), width: chartSize.width / 2) {
            sections.append(("Prediction Accuracy", .linePurple, image, nil))
        }
        if var chart = cycleLengthChart() {
            chart.isZoomable = false
            if let image = chart.renderedImage(size: chartSize) {
                let caption = fertilityWindow?.isIrregular == true ? cycleVariabilityMessage : cycleLengthNarrative(points: recentCycleLengths)
                sections.append(("Cycle Length", .lineBlue, image, caption))
            }
        }
        let bodyData = bodyTrendData
        for metric in bodyData.available {
            if let image = snapshotPlainView(BodyMetricChart(data: bodyData, metric: metric).frame(height: metric == .weight ? 240 : 300), width: chartSize.width / 2) {
                sections.append(("Body Rhythms - \(metric.longTitle)", .linePink, image, nil))
            }
        }
        if let image = snapshotPlainView(symptomReportBody, width: chartSize.width / 2) {
            sections.append(("Symptoms", .linePink, image, nil))
        }
        let timings = symptomTimings
        if !timings.isEmpty, let image = snapshotPlainView(SymptomTimingView(timings: timings, limit: 8), width: chartSize.width / 2) {
            sections.append(("Symptom Timing", .linePink, image, nil))
        }
        if let image = snapshotPlainView(moodReportBody, width: chartSize.width / 2) {
            sections.append(("Moods", .linePurple, image, nil))
        }
        let noticed = noticedTimelineItems
        if !noticed.isEmpty, let image = snapshotPlainView(NoticedTimelineView(entries: cycleHistory, items: noticed, cycleLimit: 4), width: chartSize.width / 2) {
            sections.append(("Noticed Signals", .linePurple, image, "Patterns MenoPlan noticed in the person's own logs and Apple Health data. Descriptive only, not a diagnosis."))
        }
        guard !sections.isEmpty else { return nil }
        let summaryLines = reportSummaryLines(scope: scope)

        let margin: CGFloat = 24
        let contentWidth: CGFloat = chartSize.width / 2
        let headerHeight: CGFloat = 76
        let sectionSpacing: CGFloat = 28
        let captionFont = UIFont.systemFont(ofSize: 11)
        let captionTopGap: CGFloat = 8
        let sectionHeights = sections.map { $0.image.size.height * (contentWidth / $0.image.size.width) }
        let captionHeights = sections.map { section -> CGFloat in
            guard let caption = section.caption, !caption.isEmpty else { return 0 }
            return captionTopGap + captionHeight(caption, width: contentWidth, font: captionFont)
        }
        let titleRowHeight: CGFloat = 26
        let summaryRowHeight: CGFloat = 20
        let summaryBlockHeight: CGFloat = summaryLines.isEmpty ? 0 : CGFloat(summaryLines.count) * summaryRowHeight + 18 + sectionSpacing
        let pageHeight = margin * 2 + headerHeight + summaryBlockHeight
            + zip(sectionHeights, captionHeights).reduce(0) { $0 + $1.0 + $1.1 + titleRowHeight + sectionSpacing }
        let pageWidth = contentWidth + margin * 2

        let url = FileManager.default.temporaryDirectory.appending(path: "MenoPlan-Report-\(UUID().uuidString).pdf")
        let pdfRenderer = UIGraphicsPDFRenderer(bounds: CGRect(x: 0, y: 0, width: pageWidth, height: pageHeight))
        do {
            try pdfRenderer.writePDF(to: url) { context in
                context.beginPage()
                "MenoPlan Report".draw(
                    at: CGPoint(x: margin, y: margin),
                    withAttributes: [.font: UIFont.systemFont(ofSize: 22, weight: .bold), .foregroundColor: UIColor(Color.lineNavy)]
                )
                let preparedFor = (settings?.userName.isEmpty == false) ? "Prepared for \(settings!.userName) · " : ""
                "\(preparedFor)\(scope.title) · \(DateFormatting.shortDate.string(from: .now))".draw(
                    at: CGPoint(x: margin, y: margin + 30),
                    withAttributes: [.font: UIFont.systemFont(ofSize: 13), .foregroundColor: UIColor.secondaryLabel]
                )

                var y = margin + headerHeight
                if !summaryLines.isEmpty {
                    "Summary".draw(
                        at: CGPoint(x: margin, y: y),
                        withAttributes: [.font: UIFont.systemFont(ofSize: 15, weight: .bold), .foregroundColor: UIColor(Color.lineNavy)]
                    )
                    y += 24
                    for line in summaryLines {
                        "\(line.label):".draw(
                            at: CGPoint(x: margin, y: y),
                            withAttributes: [.font: UIFont.systemFont(ofSize: 12, weight: .semibold), .foregroundColor: UIColor.secondaryLabel]
                        )
                        line.value.draw(
                            at: CGPoint(x: margin + 190, y: y),
                            withAttributes: [.font: UIFont.systemFont(ofSize: 12), .foregroundColor: UIColor(Color.lineNavy)]
                        )
                        y += summaryRowHeight
                    }
                    y += sectionSpacing
                }
                for (index, section) in sections.enumerated() {
                    section.title.draw(
                        at: CGPoint(x: margin, y: y),
                        withAttributes: [.font: UIFont.systemFont(ofSize: 16, weight: .bold), .foregroundColor: UIColor(section.tint)]
                    )
                    y += titleRowHeight
                    section.image.draw(in: CGRect(x: margin, y: y, width: contentWidth, height: sectionHeights[index]))
                    y += sectionHeights[index]
                    if let caption = section.caption, !caption.isEmpty {
                        y += captionTopGap
                        caption.draw(
                            in: CGRect(x: margin, y: y, width: contentWidth, height: captionHeights[index] - captionTopGap),
                            withAttributes: [.font: captionFont, .foregroundColor: UIColor.secondaryLabel]
                        )
                        y += captionHeights[index] - captionTopGap
                    }
                    y += sectionSpacing
                }
            }
            return url
        } catch {
            return nil
        }
    }

    @MainActor
    private func snapshotPlainView<V: View>(_ view: V, width: CGFloat) -> UIImage? {
        let renderer = ImageRenderer(content: view.frame(width: width, alignment: .leading).padding(.vertical, 4).background(Color.white))
        renderer.scale = 2
        return renderer.uiImage
    }

