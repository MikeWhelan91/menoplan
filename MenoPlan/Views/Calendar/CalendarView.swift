enum CalendarReminderTitle {
    static func display(for reminder: Reminder) -> String {
        guard reminder.isAutoGenerated else { return reminder.title }
        switch reminder.reminderType {
        case .periodExpected: return "Period may start soon"
        case .periodCheckIn: return "Did your period start?"
        case .periodLate: return "Still waiting for your period?"
        case .pregnancyRetest: return "Consider a pregnancy test"
        case .ovulationTest: return OvulationReminderCopy.startTitle
        case .fertileWindow: return OvulationReminderCopy.fertileTitle
        case .fertilePeak: return OvulationReminderCopy.peakTitle
        case .ovulationFollowUp: return reminder.title == OvulationReminderCopy.highResultTitle ? OvulationReminderCopy.highResultTitle : OvulationReminderCopy.followUpTitle
        default: return reminder.title
        }
    }

    static func detail(for reminder: Reminder, window: FertilityWindow? = nil, calendar: Calendar = .current) -> String? {
        guard reminder.isAutoGenerated else { return nil }
        switch reminder.reminderType {
        case .ovulationTest:
            guard let window else { return "Your dates are estimates; follow your test kit's instructions" }
            let date = DateFormatting.shortDate.string(from: window.predictedOvulationDate)
            return window.isIrregular
                ? "Your timing has varied; ovulation may be around \(date)"
                : "Your cycle points to around \(date); dates can shift"
        case .fertileWindow:
            guard let window else { return "These dates are a guide, not a certainty" }
            return "Your calendar suggests \(DateFormatting.shortDate.string(from: window.fertileStartDate))–\(DateFormatting.shortDate.string(from: window.fertileEndDate)); it can shift"
        case .fertilePeak:
            guard let window else { return "A best guess from your cycle, not a confirmed day" }
            return "Your cycle points to around \(DateFormatting.shortDate.string(from: window.predictedOvulationDate)); not confirmed"
        case .ovulationFollowUp:
            return reminder.title == OvulationReminderCopy.highResultTitle
                ? "Based on your saved High or Rising result; follow your kit's timing"
                : "Your window may be wider this cycle; another test may help if no peak yet"
        case .periodExpected:
            guard let predictedDate = calendar.date(byAdding: .day, value: 1, to: reminder.scheduledDate) else { return nil }
            return "Estimated for \(DateFormatting.shortDate.string(from: predictedDate)) · not confirmed"
        case .periodCheckIn where reminder.title == PeriodCheckInCopy.titleWithTest:
            return "If not, consider a pregnancy test"
        default:
            return nil
        }
    }
}

