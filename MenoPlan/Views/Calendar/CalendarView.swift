    /// `fertilityWindow` is always anchored to today's active cycle, but a
    /// chart filtered to "Last Cycle" is showing data from a different
    /// cycle entirely - overlaying today's fertile window/ovulation date on
    /// top of an unrelated cycle's temperatures would be actively wrong, not
    /// just imprecise. Resolve whichever cycle the current chart filter is
    /// actually looking at instead.
    private var chartRelevantFertilityWindow: FertilityWindow? {
        switch chartDateFilter {
        case .lastCycle:
            let sortedCycles = calendarCycleRecords.sorted { $0.startDate > $1.startDate }
            guard let active = activeCycle,
                  let activeIndex = sortedCycles.firstIndex(where: { $0.id == active.id }),
                  sortedCycles.indices.contains(activeIndex + 1) else { return nil }
            let previousCycle = sortedCycles[activeIndex + 1]
            return CycleTrackingService.window(for: previousCycle.startDate, records: calendarCycleRecords, periods: calendarPeriodEvents, settings: settings)
        case .thisCycle:
            return fertilityWindow
        case .last7Days, .last30Days, .allTime:
            // These are plain date windows, not cycle-scoped - they can
            // legitimately span a cycle boundary (e.g. the tail end of one
            // cycle's luteal phase plus the first day of the next), where
            // there's no single cycle's fertile window that correctly
            // applies to every point on screen. Overlaying today's window
            // on data that isn't from today's cycle would be actively
            // wrong, so skip the overlay rather than guess.
            return nil
        }
    }
    private var pregnancyTimeline: PregnancyTimeline? {
        // A cycle marked "ended" (including pregnancy loss) should not keep
        // producing a due-date/DPO timeline - that would misrepresent the
        // journey as still ongoing and could resurface week-by-week
