enum CalendarReminderTitle {
    static func display(for reminder: Reminder) -> String {
        guard reminder.isAutoGenerated else { return reminder.title }
        switch reminder.reminderType {
        case .periodExpected: return "Period may start soon"
        case .periodCheckIn: return "Did your period start?"
        case .periodLate: return "Still waiting for your period?"
        default: return reminder.title
        }
    }

    static func detail(for reminder: Reminder, window: FertilityWindow? = nil, calendar: Calendar = .current) -> String? {
        guard reminder.isAutoGenerated else { return nil }
        switch reminder.reminderType {
        case .periodExpected:
            guard let predictedDate = calendar.date(byAdding: .day, value: 1, to: reminder.scheduledDate) else { return nil }
            return "Estimated for \(DateFormatting.shortDate.string(from: predictedDate)) · not confirmed"
        default:
            return nil
        }
    }
}

