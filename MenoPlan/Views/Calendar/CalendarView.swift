    private func reminderRow(_ reminder: Reminder) -> some View {
        // On a phone the row is narrow, so the timestamp sits under the title.
        // On iPad that same stack left a short two-line block marooned beside
        // several hundred points of empty row, so the regular layout runs the
        // title and timestamp along one line and parks the timestamp with the
        // actions - the content then spans the row instead of hugging one edge.
        HStack(spacing: layout.isRegular ? 14 : 10) {
            reminderIcon(reminder)

            if layout.isRegular {
                VStack(alignment: .leading, spacing: 2) {
                    Text(CalendarReminderTitle.display(for: reminder))
                        .font(.lineHeadline())
                        .foregroundStyle(Color.lineNavy)
                        .fixedSize(horizontal: false, vertical: true)
                    if let detail = reminderDetail(reminder) {
                        Text(detail)
                            .font(.app(.caption))
                            .foregroundStyle(Color.lineNavy.opacity(0.62))
                            .fixedSize(horizontal: false, vertical: true)
                    }
                }

                Spacer(minLength: 16)

                if reminder.scheduledDate < .now && !reminder.isCompleted {
                    Text("Overdue")
                        .font(.app(.caption, weight: .bold))
                        .foregroundStyle(Color.linePink)
                        .fixedSize()
                }
                Text(reminderTimestamp(reminder))
                    .font(.lineSubheadline())
                    .foregroundStyle(Color.lineNavy.opacity(0.6))
                    .lineLimit(1)
                    .fixedSize()
            } else {
                VStack(alignment: .leading, spacing: 1) {
                    Text(CalendarReminderTitle.display(for: reminder))
                        .font(.lineSubheadline(.semibold))
                        .foregroundStyle(Color.lineNavy)
                        .fixedSize(horizontal: false, vertical: true)
                    Text(reminderTimestamp(reminder))
                        .font(.app(.caption))
                        .foregroundStyle(Color.lineNavy.opacity(0.58))
                        .lineLimit(1)
                    if let detail = reminderDetail(reminder) {
                        Text(detail)
                            .font(.app(.caption2))
                            .foregroundStyle(Color.lineNavy.opacity(0.62))
                            .fixedSize(horizontal: false, vertical: true)
                    }
                    if reminder.scheduledDate < .now && !reminder.isCompleted {
                        Text("Overdue")
                            .font(.app(.caption2, weight: .bold))
                            .foregroundStyle(Color.linePink)
                    }
                }
                .frame(minWidth: 0, alignment: .leading)

                // No `layoutPriority` here: the text column is already flexible,
                // and giving it priority made the HStack hand it the *whole* row
                // width before the trailing buttons were sized, so "Mark Done"
                // collapsed to nothing and the trash was pushed onto the edge.
                Spacer(minLength: 12)
            }

            markDoneButton(reminder)
            deleteReminderButton(reminder)
        }
        .padding(.horizontal, layout.isRegular ? 16 : 12)
        .padding(.vertical, 8)
        .frame(maxWidth: .infinity, minHeight: layout.isRegular ? 64 : 56)
        .background(Color.white, in: RoundedRectangle(cornerRadius: 12))
            .overlay(RoundedRectangle(cornerRadius: 12).stroke(Color.black.opacity(0.06)))
            .contentShape(Rectangle())
            .onTapGesture { reminderToEdit = reminder }
    }
