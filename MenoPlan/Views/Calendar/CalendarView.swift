private enum CalendarDayPhase: Equatable {
    case regular
    case period
    case predictedPeriod

    init(_ phase: CycleCalendarPhase) {
        switch phase {
        case .regular: self = .regular
        case .period: self = .period
        case .predictedPeriod: self = .predictedPeriod
        }
    }

    var title: String {
        switch self {
        case .regular: "Regular Day"
        case .period: "Logged Period"
        case .predictedPeriod: "Estimated Period Days"
        }
    }

    var detail: String {
        switch self {
        case .regular: "No period is logged or expected on this day."
        case .period: "This period was logged by you and starts a saved cycle."
        case .predictedPeriod: "These are the estimated days beginning with your expected period start. They are a planning estimate, not a logged period."
        }
    }

    var fill: Color {
        switch self {
        case .regular:
            Self.neutralFill
        case .period:
            // Logged period days are solid so they read as fact at a glance;
            // predictions stay as dashed outlines.
            Color.linePink
        case .predictedPeriod:
            Color.clear
        }
    }

    var accent: Color {
        switch self {
        case .regular:
            Self.neutralAccent
        case .period:
            Color.linePink
        case .predictedPeriod:
            Color.linePink.opacity(0.65)
        }
    }

    var textColor: Color {
        switch self {
        case .period: Color.white
        default: Color.lineNavy
        }
    }

    var showsPhaseBorder: Bool {
        switch self {
        case .period, .predictedPeriod: true
        case .regular: false
        }
    }

    var borderStyle: StrokeStyle {
        switch self {
        case .predictedPeriod: StrokeStyle(lineWidth: 1.5, lineCap: .round, dash: [3, 3])
        default: StrokeStyle(lineWidth: 1.25)
        }
    }

    static let neutralFill = Color(red: 0.94, green: 0.95, blue: 0.98)
    static let neutralAccent = Color(red: 0.58, green: 0.61, blue: 0.72)
    static let scanDot = Color.lineBlue.opacity(0.78)
    static let reminderDot = Color.orange
}

private struct CalendarCycleSettings {
    private let settings: UserSettings?
    private let summaryWindow: FertilityWindow?
    let lastPeriodStart: Date?
    let averageCycleLength: Int
    let lutealPhaseLength: Int
    let expectedPeriodDate: Date?
    let knownOvulationDate: Date?
    let cycleRecords: [CycleRecord]
    let periodEvents: [PeriodEvent]

    init(
        settings: UserSettings?,
        cycleRecords: [CycleRecord] = [],
        periodEvents: [PeriodEvent] = [],
        summaryWindow: FertilityWindow? = nil
    ) {
        self.settings = settings
        self.summaryWindow = summaryWindow
        lastPeriodStart = settings?.lastPeriodStartDate
        averageCycleLength = settings?.averageCycleLength ?? 28
        lutealPhaseLength = settings?.lutealPhaseLength ?? 14
        expectedPeriodDate = settings?.expectedPeriodDate
        knownOvulationDate = settings?.knownOvulationDate
        self.cycleRecords = cycleRecords
        self.periodEvents = periodEvents
    }

    func fertilityWindow(for date: Date) -> FertilityWindow? {
        let calendar = Calendar.current
        if let summaryWindow,
           calendar.startOfDay(for: date) >= calendar.startOfDay(for: summaryWindow.cycleStart),
           calendar.startOfDay(for: date) < calendar.startOfDay(for: summaryWindow.nextPeriodDate) {
            return summaryWindow
        }
        let projectionAnchor = periodEvents.map(\.startDate).max() ?? lastPeriodStart
        if let projectionAnchor,
           !FertilityWindowCalculator.isWithinProjectionHorizon(date, from: projectionAnchor, calendar: calendar) {
            return nil
        }

        // Keep the grid and the cycle summary on one calculation path.  The
        // summary uses this service too, including its handling of saved
        // ovulation dates and variable historical cycles.
        return CycleTrackingService.window(
            for: date,
            records: cycleRecords,
            periods: periodEvents,
            settings: settings,
            calendar: calendar
        )
    }

    func dayPhase(for date: Date) -> CalendarDayPhase {
        guard let window = fertilityWindow(for: date) else {
            return .regular
        }
        if CycleTrackingService.periodEvent(containing: date, in: periodEvents) == nil,
           let projected = CycleCalendarPhaseResolver.projectedWindow(for: date, from: window) {
            return CalendarDayPhase(CycleCalendarPhaseResolver.projectedPhase(for: date, window: projected))
        }

        let day = Calendar.current.startOfDay(for: date)
        return dayPhase(for: day, window: window)
    }

    func dayContext(for date: Date, trackingType: TestType) -> CalendarDayContext? {
        guard let baseWindow = fertilityWindow(for: date) else {
            // Only treat this as "just an ordinary day" when a cycle has
            // actually been tracked at some point - this date simply falls
            // outside any computable window (e.g. before the earliest logged
            // period), matching how the month grid already renders it
            // (dayPhase(for:)'s own nil-window fallback, above). A true fresh
            // install with no cycle data at all should still prompt setup.
            guard !cycleRecords.isEmpty || !periodEvents.isEmpty else { return nil }
            return CalendarDayContext(title: CalendarDayPhase.regular.title, detail: CalendarDayPhase.regular.detail, phase: .regular, cycleDay: 0, lines: [], ovulationSource: nil)
        }

        let day = Calendar.current.startOfDay(for: date)
        // Same projection the month grid uses (dayPhase(for:)), so a future
        // day in the next predicted cycle gets that cycle's phase and dates
        // instead of reading as a late day of the current one.
        let projected = CycleTrackingService.periodEvent(containing: day, in: periodEvents) == nil
            ? CycleCalendarPhaseResolver.projectedWindow(for: day, from: baseWindow)
            : nil
        let window = projected ?? baseWindow
        let cycleDay = FertilityWindowCalculator.cycleDay(for: day, cycleStart: window.cycleStart)
        let phase = projected.map { CalendarDayPhase(CycleCalendarPhaseResolver.projectedPhase(for: day, window: $0)) }
            ?? dayPhase(for: day, window: window)
        var lines: [CalendarDayDetailLine]
        switch phase {
        case .predictedPeriod:
            lines = [
                CalendarDayDetailLine(label: "Estimated start", value: DateFormatting.shortDate.string(from: window.cycleStart)),
                CalendarDayDetailLine(label: "This day", value: "Day \(cycleDay) of the estimated period")
            ]
        case .period, .regular:
            lines = [CalendarDayDetailLine(label: "Next period", value: DateFormatting.shortDate.string(from: window.nextPeriodDate))]
        }

        let title = phase == .predictedPeriod && cycleDay == 1 ? "Estimated Period Start" : phase.title
        return CalendarDayContext(title: title, detail: phase.detail, phase: phase, cycleDay: cycleDay, lines: lines, ovulationSource: nil)
    }

    private func dateBelongsToCycle(_ date: Date, window: FertilityWindow, graceDays: Int = 0) -> Bool {
        let calendar = Calendar.current
        let day = calendar.startOfDay(for: date)
        let start = calendar.startOfDay(for: window.cycleStart)
        let end = calendar.startOfDay(
            for: calendar.date(byAdding: .day, value: graceDays, to: window.nextPeriodDate)
                ?? window.nextPeriodDate
        )
        return day >= start && day <= end
    }

    private func dayPhase(for day: Date, window: FertilityWindow) -> CalendarDayPhase {
        CalendarDayPhase(CycleCalendarPhaseResolver.phase(
            for: day,
            window: window,
            cycleRecords: cycleRecords,
            periodEvents: periodEvents
        ))
    }

