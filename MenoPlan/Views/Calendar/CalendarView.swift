    /// for a live chart view instead of the real drawing - each chart is
    /// rasterized through DGLineChart/DGBarChart's own renderedImage(size:)
    /// instead, which uses DGCharts' native export path. Plain SwiftUI
    /// content (the symptom/mood summaries) doesn't have that problem and
    /// still goes through ImageRenderer.
    private func captionHeight(_ text: String, width: CGFloat, font: UIFont) -> CGFloat {
        let bounding = (text as NSString).boundingRect(
            with: CGSize(width: width, height: .greatestFiniteMagnitude),
            options: [.usesLineFragmentOrigin, .usesFontLeading],
            attributes: [.font: font],
            context: nil
        )
        return ceil(bounding.height)
    }

