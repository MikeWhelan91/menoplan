            // legitimately span a cycle boundary (e.g. the tail end of one
            // cycle's luteal phase plus the first day of the next), where
            // there's no single cycle's fertile window that correctly
            // applies to every point on screen. Overlaying today's window
            // on data that isn't from today's cycle would be actively
            // wrong, so skip the overlay rather than guess.
            return nil
        }
