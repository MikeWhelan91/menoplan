private struct InlineCalendarMonthView: View {
    @Binding var monthAnchor: Date
    var cycleSettings: CalendarCycleSettings
    var scans: [Scan]
    var reminders: [Reminder]
    var dailyLogs: [DailyFertilityLog]
    /// Non-nil while "Edit period dates" is active: taps toggle a day in the
    /// set instead of opening the day sheet.
    var editSelection: Binding<Set<Date>>? = nil
    var selectDate: (Date) -> Void

    @Environment(\.lineLayout) private var layout
    @State private var gridWidth: CGFloat = 0
    @State private var slideForward = true

    private func changeMonth(by delta: Int) {
        slideForward = delta > 0
        withAnimation(.spring(response: 0.42, dampingFraction: 0.88)) {
            monthAnchor = Calendar.current.date(byAdding: .month, value: delta, to: startOfMonth(for: monthAnchor)) ?? monthAnchor
        }
    }

    private let columnSpacing: CGFloat = 6
    private var columns: [GridItem] { Array(repeating: GridItem(.flexible(), spacing: columnSpacing), count: 7) }

    /// On a wide grid the day circle grows to fill its column instead of
    /// sitting as a fixed 30pt dot in the middle of it. An iPad's grid is
    /// ~2.5x wider than a phone's, so a fixed diameter reads as seven tiny
    /// marks marooned in white space. Capped so a very wide column doesn't
    /// produce comically large circles, and left at the phone's long-standing
    /// 30pt on compact so that layout is untouched.
    private var dayDiameter: CGFloat {
        guard layout.isRegular, gridWidth > 0 else { return 30 }
        let column = (gridWidth - columnSpacing * 6) / 7
        return min(max(30, column - 6), 64)
    }

    /// The grid stops widening once the columns are comfortably larger than the
    /// circles in them. Without this the 13" iPad spread seven 54pt circles
    /// across 114pt columns, which read as a scattering of dots rather than a
    /// calendar - the circle cap alone can't fix that, because the columns keep
    /// growing after the circles stop.
    private var gridMaxWidth: CGFloat {
        layout.isRegular ? 620 : .infinity
    }

    private var dotSize: CGFloat { max(5, dayDiameter * 0.13) }

    var body: some View {
        VStack(spacing: 12) {
            HStack {
                Button {
                    changeMonth(by: -1)
                } label: {
                    Image(systemName: "chevron.left")
                        .font(.app(.caption, weight: .bold))
                        .foregroundStyle(Color.lineNavy)
                        .frame(width: 34, height: 34)
                        .background(Color.lineBackground, in: Circle())
                }
                .buttonStyle(.plain)

                Spacer()

                // Month and year slide together as one title, matching the grid.
                ZStack {
                    Text(startOfMonth(for: monthAnchor).formatted(.dateTime.month(.wide).year()))
                        .font(.app(size: LineType.size(20), weight: .bold))
                        .foregroundStyle(Color.lineNavy)
                        .id(startOfMonth(for: monthAnchor))
                        .transition(.push(from: slideForward ? .trailing : .leading))
                }
                .clipped()

                Spacer()

                Button {
                    changeMonth(by: 1)
                } label: {
                    Image(systemName: "chevron.right")
                        .font(.app(.caption, weight: .bold))
                        .foregroundStyle(Color.lineNavy)
                        .frame(width: 34, height: 34)
                        .background(Color.lineBackground, in: Circle())
                }
                .buttonStyle(.plain)
            }

            // Header row and grid share one width so the weekday labels stay
            // over their own columns - capping only the grid left "Sun" and
            // "Sat" pinned to the card's edges with the dates bunched between.
            VStack(spacing: 12) {
                HStack(spacing: columnSpacing) {
                    ForEach(CalendarMonthLayout.weekdaySymbols(), id: \.self) { symbol in
                        Text(symbol)
                            .font(.app(size: max(11, dayDiameter * 0.30), weight: .bold))
                            .foregroundStyle(Color.lineNavy.opacity(0.42))
                            .frame(maxWidth: .infinity)
                    }
                }

                ZStack {
                    LazyVGrid(columns: columns, spacing: 8) {
                        ForEach(Array(monthCells.enumerated()), id: \.offset) { _, cell in
                            if let date = cell {
                                monthDay(date)
                            } else {
                                Color.clear.frame(height: rowHeight)
                            }
                        }
                    }
                    .id(startOfMonth(for: monthAnchor))
                    .transition(.asymmetric(
                        insertion: .move(edge: slideForward ? .trailing : .leading).combined(with: .opacity),
                        removal: .move(edge: slideForward ? .leading : .trailing).combined(with: .opacity)
                    ))
                }
                .clipped()
                .contentShape(Rectangle())
                .simultaneousGesture(
                    DragGesture(minimumDistance: 24)
                        .onEnded { value in
                            guard abs(value.translation.width) > abs(value.translation.height) * 1.5,
                                  abs(value.translation.width) > 50 else { return }
                            changeMonth(by: value.translation.width < 0 ? 1 : -1)
                        }
                )
            }
            .onGeometryChange(for: CGFloat.self) { $0.size.width } action: { gridWidth = $0 }
            .frame(maxWidth: gridMaxWidth)
            .frame(maxWidth: .infinity)
        }
        .padding(14)
        .background(
            LinearGradient(
                colors: [Color.white.opacity(0.97), Color.linePurple.opacity(0.07)],
                startPoint: .topLeading,
                endPoint: .bottomTrailing
            ),
            in: RoundedRectangle(cornerRadius: 18, style: .continuous)
        )
        .overlay(RoundedRectangle(cornerRadius: 18, style: .continuous).stroke(Color.linePurple.opacity(0.13), lineWidth: 1))
    }

    private var monthCells: [Date?] {
        CalendarMonthLayout.cells(for: monthAnchor)
    }

    private func monthDay(_ date: Date) -> some View {
        let calendar = Calendar.current
        let phase = cycleSettings.dayPhase(for: date)
        let hasScan = scans.contains { calendar.isDate($0.createdAt, inSameDayAs: date) }
        let hasReminder = reminders.contains { calendar.isDate($0.scheduledDate, inSameDayAs: date) }
        let isToday = calendar.isDateInToday(date)

        if let editSelection {
            return AnyView(periodEditDay(date, selection: editSelection))
        }

        return AnyView(Button {
            selectDate(date)
        } label: {
            VStack(spacing: 4) {
                Text(date.formatted(.dateTime.day()))
                    .font(.app(size: max(12, dayDiameter * 0.40), weight: .bold))
                    .frame(width: dayDiameter, height: dayDiameter)
                    .background(phase.fill, in: Circle())
                    .foregroundStyle(phase.textColor)
                    .overlay {
                        if phase.showsPhaseBorder {
                            Circle().stroke(phase.accent.opacity(0.72), style: phase.borderStyle)
                        }
                        // Padded outward so it doesn't paint over (and
                        // visually erase) a pale phase fill/border - see the
                        // matching comment in fertilityStrip above.
                        if isToday {
                            CalendarTodayMarker()
                        }
                    }

                CalendarEventMarkers(hasScan: hasScan, hasReminder: hasReminder, size: dotSize)
            }
            .frame(maxWidth: .infinity, minHeight: rowHeight)
        }
        .buttonStyle(.plain))
    }

    /// Edit-mode day: a toggle. Selected days fill pink with a tick; future
    /// days can't be logged, matching the rest of Calendar.
    private func periodEditDay(_ date: Date, selection: Binding<Set<Date>>) -> some View {
        let calendar = Calendar.current
        let day = calendar.startOfDay(for: date)
        let isSelected = selection.wrappedValue.contains(day)
        let isFuture = day > calendar.startOfDay(for: .now)
        return Button {
            guard !isFuture else { return }
            UISelectionFeedbackGenerator().selectionChanged()
            withAnimation(.spring(response: 0.3, dampingFraction: 0.65)) {
                if isSelected { selection.wrappedValue.remove(day) } else { selection.wrappedValue.insert(day) }
            }
        } label: {
            VStack(spacing: 4) {
                Text(date.formatted(.dateTime.day()))
                    .font(.app(size: max(12, dayDiameter * 0.40), weight: .bold))
                    .foregroundStyle(isSelected ? Color.white : Color.lineNavy.opacity(isFuture ? 0.3 : 1))
                    .frame(width: dayDiameter, height: dayDiameter)
                    .background(isSelected ? Color.linePink : Color.clear, in: Circle())
                    .overlay {
                        Circle().stroke(isSelected ? Color.clear : Color.linePink.opacity(isFuture ? 0.15 : 0.45), style: StrokeStyle(lineWidth: 1.4, dash: [3, 3]))
                    }
                    .overlay(alignment: .bottomTrailing) {
                        if isSelected {
                            Image(systemName: "checkmark.circle.fill")
                                .font(.system(size: max(11, dayDiameter * 0.34), weight: .bold))
                                .foregroundStyle(Color.white, Color.linePink)
                                .background(Circle().fill(Color.white).padding(1))
                                .offset(x: 4, y: 4)
                                .transition(.scale.combined(with: .opacity))
                        }
                    }
                    .scaleEffect(isSelected ? 1.04 : 1)
                Color.clear.frame(height: dotSize)
            }
            .frame(maxWidth: .infinity, minHeight: rowHeight)
        }
        .buttonStyle(.plain)
        .disabled(isFuture)
        .accessibilityLabel(date.formatted(date: .long, time: .omitted))
        .accessibilityAddTraits(isSelected ? .isSelected : [])
    }

    private var rowHeight: CGFloat { dayDiameter + dotSize + 4 }

    private func startOfMonth(for date: Date) -> Date {
        let calendar = Calendar.current
        let components = calendar.dateComponents([.year, .month], from: date)
        return calendar.date(from: components) ?? calendar.startOfDay(for: date)
    }
