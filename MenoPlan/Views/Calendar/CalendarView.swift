    /// nil means no date restriction ("All Time"). "This Cycle"/"Last Cycle" fall back to nil
    /// when there isn't a matching cycle record yet, rather than showing an empty chart for a
    /// filter that doesn't apply.
    private var chartDateRange: ClosedRange<Date>? {
        let now = Date.now
        switch chartDateFilter {
        case .last7Days:
            return (Calendar.current.date(byAdding: .day, value: -7, to: now) ?? .distantPast)...now
        case .last30Days:
            return (Calendar.current.date(byAdding: .day, value: -30, to: now) ?? .distantPast)...now
        case .thisCycle:
            guard let cycle = activeCycle else { return nil }
            return cycle.startDate...(cycle.endDate ?? now)
        case .lastCycle:
            let sortedCycles = calendarCycleRecords.sorted { $0.startDate > $1.startDate }
            guard let active = activeCycle,
                  let activeIndex = sortedCycles.firstIndex(where: { $0.id == active.id }),
                  sortedCycles.indices.contains(activeIndex + 1) else { return nil }
            let previous = sortedCycles[activeIndex + 1]
            return previous.startDate...(previous.endDate ?? previous.startDate)
        case .allTime:
            return nil
        }
    }

    private func filteredByChartDate<T>(_ items: [T], date: (T) -> Date) -> [T] {
        guard let range = chartDateRange else { return items }
        return items.filter { range.contains(date($0)) }
    }

