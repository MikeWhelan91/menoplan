    /// Silent, throttled - checked hourly while Calendar is active but runs at most once every
    /// 6 hours. It never shows a toast, since this is a background refresh rather than the
    /// user-initiated sync in Settings (which does report back what it imported).
    private func autoSyncHealthKitIfNeeded() async {
        guard let settings, settings.healthKitSyncEnabled else { return }
        if let last = settings.lastHealthKitSyncDate, Date.now.timeIntervalSince(last) < 6 * 60 * 60 { return }
        _ = try? await HealthKitSyncService.sync(settings: settings, context: modelContext)
    }

    private func beginScanFromCalendar(_ testType: TestType, on selectedDay: Date, today: Date) {
        selectedDate = nil
        let historicalDate: Date? = selectedDay < today
            ? Calendar.current.date(
                bySettingHour: Calendar.current.component(.hour, from: .now),
                minute: Calendar.current.component(.minute, from: .now),
                second: 0,
                of: selectedDay
            )
            : nil

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) {
            appState.startScan(testType: testType, testDate: historicalDate)
        }
    }

