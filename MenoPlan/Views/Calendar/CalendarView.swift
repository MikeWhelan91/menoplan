        let hasScan = scans.contains { calendar.isDate($0.createdAt, inSameDayAs: date) }
        let reminder = reminders.contains { calendar.isDate($0.scheduledDate, inSameDayAs: date) }

        return Button {
            onSelectDate(date)
            dismiss()
        } label: {
            VStack(spacing: 6) {
                Text(date.formatted(.dateTime.day()))
                    .font(.app(size: max(13, dayDiameter * 0.38), weight: .semibold))
                    .foregroundStyle(isFuture ? phase.textColor.opacity(0.42) : phase.textColor)
                    .frame(width: dayDiameter, height: dayDiameter)
                    .background(phase.fill, in: Circle())
                    .overlay {
                        if phase.showsPhaseBorder {
                            Circle().stroke(phase.accent.opacity(0.72), style: phase.borderStyle)
                        }
                        if isToday {
                            CalendarTodayMarker()
                        }
                    }

                CalendarEventMarkers(hasScan: hasScan, hasReminder: reminder, size: dotSize)
            }
            .frame(maxWidth: .infinity, minHeight: rowHeight)
        }
        .buttonStyle(.plain)
    }

    private static func startOfMonth(for date: Date) -> Date {
        let calendar = Calendar.current
        let components = calendar.dateComponents([.year, .month], from: date)
        return calendar.date(from: components) ?? calendar.startOfDay(for: date)
    }
}

/// Twelve mini months per year, tinted the same way as the month grid, so a
/// whole year of logged and predicted periods reads at a glance.
private struct FullCalendarYearView: View {
    let cycleSettings: CalendarCycleSettings
    let focusMonth: Date
    var onSelectMonth: (Date) -> Void

    private var years: [Int] {
        let current = Calendar.current.component(.year, from: .now)
        return [current - 1, current, current + 1]
    }

    var body: some View {
        ScrollViewReader { reader in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: 22) {
                    ForEach(years, id: \.self) { year in
                        VStack(alignment: .leading, spacing: 12) {
                            Text(String(year))
                                .font(.app(size: LineType.size(26), weight: .heavy))
                                .foregroundStyle(Color.lineNavy)
                            LazyVGrid(columns: Array(repeating: GridItem(.flexible(), spacing: 14), count: 3), spacing: 18) {
                                ForEach(1...12, id: \.self) { month in
                                    if let date = Calendar.current.date(from: DateComponents(year: year, month: month, day: 1)) {
                                        Button { onSelectMonth(date) } label: { miniMonth(date) }
                                            .buttonStyle(PressScaleButtonStyle())
                                    }
                                }
                            }
                        }
                        .id(year)
                    }
                }
                .padding(.vertical, 4)
            }
            .onAppear { reader.scrollTo(Calendar.current.component(.year, from: focusMonth), anchor: .top) }
        }
    }

    private func miniMonth(_ month: Date) -> some View {
        let calendar = Calendar.current
        let isCurrentMonth = calendar.isDate(month, equalTo: .now, toGranularity: .month)
        return VStack(alignment: .leading, spacing: 5) {
            Text(month.formatted(.dateTime.month(.wide)))
                .font(.app(size: LineType.size(13), weight: isCurrentMonth ? .heavy : .bold))
                .foregroundStyle(isCurrentMonth ? Color.linePink : Color.lineNavy)
            LazyVGrid(columns: Array(repeating: GridItem(.flexible(), spacing: 1), count: 7), spacing: 2) {
                ForEach(Array(CalendarMonthLayout.cells(for: month).enumerated()), id: \.offset) { _, cell in
                    if let day = cell {
                        miniDay(day)
                    } else {
                        Color.clear.frame(height: 13)
                    }
                }
            }
        }
        .padding(8)
        .background(Color.white.opacity(isCurrentMonth ? 1 : 0.75), in: RoundedRectangle(cornerRadius: 12, style: .continuous))
    }

    private func miniDay(_ day: Date) -> some View {
        let phase = cycleSettings.dayPhase(for: day)
        let isToday = Calendar.current.isDateInToday(day)
        return Text(day.formatted(.dateTime.day()))
            .font(.app(size: 8.5, weight: isToday ? .heavy : .semibold))
            .foregroundStyle(miniText(phase))
            .frame(width: 13, height: 13)
            .background {
                if phase == .period { Circle().fill(Color.linePink) }
            }
            .overlay {
                if phase == .predictedPeriod {
                    Circle().stroke(Color.linePink.opacity(0.7), style: StrokeStyle(lineWidth: 0.8, dash: [1.5, 1.5]))
                } else if isToday {
                    Circle().stroke(Color.lineNavy, lineWidth: 1)
                }
            }
    }

    private func miniText(_ phase: CalendarDayPhase) -> Color {
        switch phase {
        case .period: .white
        case .predictedPeriod: .linePink
        default: Color.lineNavy.opacity(0.8)
        }
    }
}

struct ReminderEditorView: View {
    @Environment(\.dismiss) private var dismiss
    @Environment(\.modelContext) private var modelContext
    @Environment(AppState.self) private var appState
    @Query(sort: \CycleRecord.startDate) private var cycles: [CycleRecord]
    @State private var type: ReminderType
    @State private var title: String
    @State private var date: Date
    private let existing: Reminder?

    init(initialType: ReminderType = .periodExpected, initialDate: Date? = nil, initialTitle: String? = nil) {
        existing = nil
        _type = State(initialValue: initialType)
        _title = State(initialValue: initialTitle ?? initialType.title)
        _date = State(initialValue: initialDate ?? Self.defaultDate(for: initialType))
    }

    init(editing reminder: Reminder) {
        existing = reminder
        _type = State(initialValue: reminder.reminderType)
        _title = State(initialValue: reminder.title)
        _date = State(initialValue: reminder.scheduledDate)
    }

    var body: some View {
        VStack(spacing: 18) {
            HStack(alignment: .center) {
                VStack(alignment: .leading, spacing: 3) {
                    Text(existing == nil ? "Add reminder" : "Edit reminder")
                        .font(.app(size: LineType.size(25), weight: .bold))
                        .foregroundStyle(Color.lineNavy)
                    Text("A gentle nudge, when you need it.")
                        .font(.lineCaption())
                        .foregroundStyle(Color.lineNavy.opacity(0.58))
                }
                Spacer()
                Button(action: { dismiss() }) {
                    Image(systemName: "xmark")
                        .font(.system(size: LineType.size(13), weight: .bold))
                        .foregroundStyle(Color.lineNavy.opacity(0.68))
                        .frame(width: 34, height: 34)
                        .background(Color.lineNavy.opacity(0.07), in: Circle())
                }
                .buttonStyle(.plain)
                .accessibilityLabel("Cancel")
            }

            VStack(spacing: 0) {
                compactField("Type") {
                    Menu {
                        ForEach(ReminderType.allCases) { reminderType in
                            Button {
                                type = reminderType
                                title = reminderType.title
                            } label: {
                                Text(reminderType.title)
                                    .lineLimit(1)
                            }
                        }
                    } label: {
                        HStack(spacing: 6) {
                            Text(type.title)
                                .lineLimit(1)
                                .minimumScaleFactor(0.78)
                            Image(systemName: "chevron.up.chevron.down")
                                .font(.app(.caption, weight: .semibold))
                        }
                        .foregroundStyle(Color.lineNavy)
                        .frame(minWidth: 185, alignment: .trailing)
                    }
                    .tint(Color.linePurple)
                }

                Divider()

                TextField("What should we remind you about?", text: $title)
                    .font(.lineSubheadline())
                    .padding(.vertical, 14)

                Divider()

                compactField("When") {
                    DatePicker("When", selection: $date, displayedComponents: [.date, .hourAndMinute])
                        .labelsHidden()
                        .tint(Color.linePurple)
                }
            }
            .padding(.horizontal, 14)
            .background(Color.white.opacity(0.88), in: RoundedRectangle(cornerRadius: 18, style: .continuous))
            .overlay(RoundedRectangle(cornerRadius: 18, style: .continuous).stroke(Color.lineNavy.opacity(0.07)))

            Button(existing == nil ? "Save reminder" : "Save changes") { save() }
                .buttonStyle(.primaryLine)
        }
        .padding(22)
        .background { LineCheckBrandBackdrop() }
        .presentationDetents([.height(420)])
        .presentationCornerRadius(30)
        .presentationDragIndicator(.visible)
        .tint(Color.lineBlue)
    }

    private func compactField<Content: View>(_ label: String, @ViewBuilder content: () -> Content) -> some View {
        HStack(spacing: 12) {
            Text(label)
                .font(.lineSubheadline(.semibold))
                .foregroundStyle(Color.lineNavy.opacity(0.68))
            Spacer(minLength: 12)
            content()
                .multilineTextAlignment(.trailing)
        }
        .padding(.vertical, 12)
    }

    private static func defaultDate(for type: ReminderType) -> Date {
        switch type {
        case .ovulationTest, .periodExpected, .periodCheckIn, .periodLate, .logTestResult, .bodyCheckIn, .cycleSetup:
            Calendar.current.date(byAdding: .day, value: 1, to: .now) ?? .now
        case .medication, .custom:
            Calendar.current.date(byAdding: .hour, value: 24, to: .now) ?? .now
        }
    }

    private func save() {
        let reminder = existing ?? Reminder(title: title, reminderType: type, scheduledDate: date)
        reminder.title = title
        reminder.reminderTypeRaw = type.rawValue
        reminder.scheduledDate = date
        reminder.isCompleted = false
        reminder.completedAt = nil
        reminder.cycleRecordID = CycleTrackingService.activeCycle(on: date, records: cycles)?.id
        let notification = ReminderNotification(reminder: reminder)
        if existing == nil {
            modelContext.insert(reminder)
            AppAnalytics.log("linecheck_reminder_created", ["reminder_type": type.rawValue])
        }
        Task {
            let notificationsEnabled = await NotificationService().requestPermission()
            var notificationScheduled = false
            if notificationsEnabled {
                do {
                    try await NotificationService().schedule(notification)
                    notificationScheduled = true
                } catch {
                    notificationScheduled = false
                }
            }
            await MainActor.run {
                appState.settings?.notificationsEnabled = notificationsEnabled
                try? modelContext.save()
                if notificationScheduled {
                    appState.toast = "Reminder added and notification scheduled"
                } else if notificationsEnabled {
                    appState.toast = "Reminder added, but notification scheduling failed"
                } else {
                    appState.toast = "Reminder added without notifications"
                }
                dismiss()
            }
        }
    }
}

