    /// and compact keeps the phone's 34pt. This sheet is wider than the inline
    /// grid, so it gets a correspondingly larger cap.
    private var dayDiameter: CGFloat {
        guard layout.isRegular, gridWidth > 0 else { return 34 }
        let column = (gridWidth - columnSpacing * 6) / 7
        return min(max(34, column - 8), 62)
    }

