    /// The irregular-cycle warning already explains a genuinely erratic
    /// history - this instead describes a directional trend (lengthening,
    /// shortening, steady) worth naming even when cycles aren't erratic
    /// enough to trip that warning.
    private func cycleLengthNarrative(points: [CycleLengthPoint]) -> String? {
        guard points.count >= 3 else { return nil }
        let lengths = points.map(\.length)
        let recentCount = min(3, lengths.count)
        let recent = lengths.suffix(recentCount)
        let earlier = lengths.dropLast(recentCount)
        guard !earlier.isEmpty else { return nil }
        let recentAvg = Double(recent.reduce(0, +)) / Double(recent.count)
        let earlierAvg = Double(earlier.reduce(0, +)) / Double(earlier.count)
        let delta = recentAvg - earlierAvg
        if delta >= 2 {
            return "Your most recent cycles have run about \(delta.formatted(.number.precision(.fractionLength(0)))) days longer on average than your earlier ones."
        } else if delta <= -2 {
            return "Your most recent cycles have run about \(abs(delta).formatted(.number.precision(.fractionLength(0)))) days shorter on average than your earlier ones."
        } else {
            return "Your cycle length has stayed fairly steady, averaging \(Int(recentAvg.rounded())) days over your last \(recentCount) cycles."
        }
    }

