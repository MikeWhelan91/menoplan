    private func healthSummary(_ metrics: DailyHealthMetrics) -> String {
        var parts: [String] = []
        if let steps = metrics.steps { parts.append("\(steps.formatted(.number.precision(.fractionLength(0)))) steps") }
        if let sleep = metrics.sleepHours, sleep > 0 { parts.append(String(format: "%.1fh sleep", sleep)) }
        if let exercise = metrics.exerciseMinutes, exercise > 0 { parts.append("\(Int(exercise.rounded())) min exercise") }
        if let resting = metrics.restingHeartRate { parts.append("resting HR \(Int(resting.rounded()))") }
        if let hrv = metrics.heartRateVariabilityMs { parts.append("HRV \(Int(hrv.rounded())) ms") }
        return parts.joined(separator: " · ")
    }

    private func temperatureText(_ celsius: Double) -> String {
        let display = temperatureUnit == .fahrenheit ? celsius * 9 / 5 + 32 : celsius
        return String(format: "%.2f%@", display, temperatureUnit.title)
    }

    private func logLines(_ log: DailyFertilityLog) -> [(String, String, String)] {
        var rows: [(String, String, String)] = []
        if let flow = log.flowIntensity { rows.append(("Flow", flow.title, "drop.circle.fill")) }
        if let bbt = log.basalBodyTemperatureCelsius { rows.append(("Basal body temperature", temperatureText(bbt), "thermometer.medium")) }
        if let wrist = log.wristTemperatureCelsius { rows.append(("Apple Watch wrist temperature", temperatureText(wrist), "applewatch")) }
        if let weight = log.weightKg { rows.append(("Weight", weightUnit.formatted(weight), "scalemass.fill")) }
        if let water = log.waterMl { rows.append(("Water", bodyUnit.formattedWater(water), "drop.fill")) }
        if !log.symptoms.isEmpty { rows.append(("Symptoms", log.symptoms.joined(separator: ", "), "waveform.path.ecg")) }
        if let value = log.cervicalMucusRaw { rows.append(("Cervical mucus", value, "drop.fill")) }
        if let value = log.cervicalPositionRaw { rows.append(("Cervical position", value, "arrow.up.and.down.circle")) }
        if let value = log.inseminationRaw { rows.append(("Insemination", value, "cross.vial")) }
        if let value = log.sexRaw { rows.append(("Sex", value, "heart.fill")) }
        if !log.moods.isEmpty { rows.append(("Mood", log.moods.joined(separator: ", "), "face.smiling")) }
        if !log.supplements.isEmpty { rows.append(("Supplements", log.supplements.joined(separator: ", "), "pills.fill")) }
        if !log.notes.isEmpty { rows.append(("Notes", log.notes, "note.text")) }
        return rows
    }

    private func dayStat(_ line: CalendarDayDetailLine, context: CalendarDayContext) -> some View {
        let isDPO = line.label == "Days past ovulation"

        return VStack(alignment: .leading, spacing: 8) {
