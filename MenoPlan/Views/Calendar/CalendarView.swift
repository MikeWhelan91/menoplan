                        slideForward = month > monthAnchor
                        monthAnchor = Self.startOfMonth(for: month)
                        withAnimation(.spring(response: 0.45, dampingFraction: 0.88)) { showsYear = false }
                    }
                    .transition(.asymmetric(insertion: .scale(scale: 1.08).combined(with: .opacity), removal: .scale(scale: 1.08).combined(with: .opacity)))
