    private var weekdayHeader: some View {
        let symbols = CalendarMonthLayout.weekdaySymbols()
        return HStack(spacing: columnSpacing) {
            ForEach(symbols, id: \.self) { symbol in
                Text(symbol)
                    .font(.app(size: max(12, dayDiameter * 0.28), weight: .bold))
                    .foregroundStyle(Color.lineNavy.opacity(0.42))
                    .frame(maxWidth: .infinity)
            }
        }
        .padding(.horizontal, 16)
    }

    private var monthCells: [Date?] {
        CalendarMonthLayout.cells(for: monthAnchor)
    }

    private func monthDay(_ date: Date) -> some View {
        let calendar = Calendar.current
        let isToday = calendar.isDateInToday(date)
        let isFuture = calendar.startOfDay(for: date) > calendar.startOfDay(for: .now)
        let phase = cycleSettings.dayPhase(for: date)
        let hasScan = scans.contains { calendar.isDate($0.createdAt, inSameDayAs: date) }
        let reminder = reminders.contains { calendar.isDate($0.scheduledDate, inSameDayAs: date) }
        let hasSex = dailyLogs.contains { log in
            calendar.isDate(log.date, inSameDayAs: date) &&
            log.sexRaw?.localizedCaseInsensitiveCompare("No Sex") != .orderedSame &&
            log.sexRaw?.isEmpty == false
        }

        return Button {
            onSelectDate(date)
            dismiss()
        } label: {
            VStack(spacing: 6) {
                Text(date.formatted(.dateTime.day()))
                    .font(.app(size: max(13, dayDiameter * 0.38), weight: .semibold))
                    .foregroundStyle(isFuture ? phase.textColor.opacity(0.42) : phase.textColor)
                    .frame(width: dayDiameter, height: dayDiameter)
                    .background(phase.fill, in: Circle())
                    .overlay {
                        if phase.showsPhaseBorder {
                            Circle().stroke(phase.accent.opacity(0.72), style: phase.borderStyle)
                        }
                        if phase.showsEstimateRing {
                            CalendarEstimateRing()
                        }
                        if isToday {
                            CalendarTodayMarker()
                        }
                    }

                CalendarEventMarkers(hasScan: hasScan, hasReminder: reminder, hasSex: hasSex, size: dotSize)
            }
            .frame(maxWidth: .infinity, minHeight: rowHeight)
        }
        .buttonStyle(.plain)
    }

    private static func startOfMonth(for date: Date) -> Date {
        let calendar = Calendar.current
        let components = calendar.dateComponents([.year, .month], from: date)
        return calendar.date(from: components) ?? calendar.startOfDay(for: date)
    }
