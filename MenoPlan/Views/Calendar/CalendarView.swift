                    guard let loggedPeriod else { return nil }
                    let start = Calendar.current.startOfDay(for: loggedPeriod.startDate)
                    let end = Calendar.current.startOfDay(for: loggedPeriod.endDate ?? Calendar.current.date(byAdding: .day, value: 4, to: start) ?? start)
