    private func journalInsight(values: (DailyFertilityLog) -> [String], noun: String) -> String? {
        // Timing (which phase) lives in the Pro Symptom Timing card; this
        // free line only covers what tends to be logged together.
        let logs = recentJournalLogs.filter { !values($0).isEmpty }
        guard logs.count >= 4 else { return nil }

        var pairCounts: [String: Int] = [:]
        for log in logs {
            let labels = Array(Set(values(log))).sorted()
            guard labels.count >= 2 else { continue }
            for index in labels.indices {
                for otherIndex in labels.index(after: index)..<labels.endIndex {
                    pairCounts["\(labels[index]) and \(labels[otherIndex])", default: 0] += 1
                }
            }
        }
        if let pair = pairCounts.max(by: { $0.value < $1.value }), pair.value >= 2 {
            return "Insight: \(pair.key) were logged together on \(pair.value) days."
        }
        return nil
    }

