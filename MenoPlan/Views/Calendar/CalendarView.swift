/// Lower bound for period/ovulation date pickers - generous enough for real
/// history, but stops an obviously mistyped date (e.g. the wrong decade)
/// from producing a nonsensical multi-year cycle history.
private let earliestReasonableCycleDate = Calendar.current.date(byAdding: .year, value: -3, to: .now) ?? .distantPast

