    private func deletePeriod(_ period: PeriodEvent) {
        AppAnalytics.log("linecheck_period_deleted")
        let remainingPeriods = calendarPeriodEvents.filter { $0.id != period.id }
        let targetCycle = calendarCycleRecords.first { $0.id == period.cycleRecordID }
        var cycleToResync: CycleRecord?
        if let targetCycle {
            let remainingCycles = calendarCycleRecords.filter { $0.id != targetCycle.id }.sorted { $0.startDate < $1.startDate }
            let previous = remainingCycles.last { $0.startDate < targetCycle.startDate }
            let next = remainingCycles.first { $0.startDate > targetCycle.startDate }
            previous?.endDate = next?.startDate
            previous?.status = next == nil ? .active : .completed
            for scan in scans where scan.cycleRecordID == targetCycle.id { scan.cycleRecordID = nil }
            let notificationService = NotificationService()
            for reminder in reminders where reminder.isAutoGenerated && reminder.cycleRecordID == targetCycle.id {
                notificationService.cancel(id: reminder.id)
                modelContext.delete(reminder)
            }
            modelContext.delete(targetCycle)
            for scan in scans where scan.cycleRecordID == nil { CycleTrackingService.attach(scan, to: remainingCycles) }
            cycleToResync = CycleTrackingService.activeCycle(records: remainingCycles)
        }
        modelContext.delete(period)
        if let settings {
            settings.lastPeriodStartDate = remainingPeriods.map(\.startDate).max()
            settings.averageCycleLength = CycleTrackingService.learnedAverageCycleLength(from: remainingPeriods, fallback: settings.averageCycleLength)
        }
        try? modelContext.save()
        if let settings, let cycleToResync,
           let recalculated = CycleTrackingService.window(
               records: (try? modelContext.fetch(FetchDescriptor<CycleRecord>())) ?? [cycleToResync],
               periods: remainingPeriods, settings: settings
           ) {
            Task {
                await ReminderAutomationService.syncPredictedReminders(
                    cycle: cycleToResync,
                    window: recalculated,
                    settings: settings,
                    existingReminders: reminders,
                    context: modelContext
                )
            }
        }
        appState.toast = "Period deleted and predictions updated"
    }

    private func resyncReminders(for cycle: CycleRecord) {
        // Anchor to the cycle being edited, not "today" - without this, editing
        // a past (non-active) cycle would resolve today's active cycle's window
        // instead and reschedule reminders under the wrong cycle's dates.
        guard let settings, let window = CycleTrackingService.window(for: cycle.startDate, records: calendarCycleRecords, periods: calendarPeriodEvents, settings: settings) else { return }
        Task {
            await ReminderAutomationService.syncPredictedReminders(
                cycle: cycle,
                window: window,
                settings: settings,
                existingReminders: reminders,
                context: modelContext
            )
        }
    }

    /// Trims one day off either end of a logged period. A period is stored
    /// as a contiguous start...end range, so only its first or last day can
    /// be removed this way - the caller (removableDayEdge) never offers this
    /// for a day in the middle of the range.
    private func removeDay(_ day: Date, edge: PeriodDayEdge, from period: PeriodEvent) {
        let calendar = Calendar.current
        switch edge {
        case .last:
            // Trimming the end doesn't move cycle day 1, so no prediction
            // needs recalculating - only which days render as "period" changes.
            guard let newEnd = calendar.date(byAdding: .day, value: -1, to: day) else { return }
            period.endDate = calendar.startOfDay(for: newEnd)
        case .first:
            guard let newStart = calendar.date(byAdding: .day, value: 1, to: day) else { return }
            // A period/cycle start date can never be later than today - once
            // it is, FertilityWindowCalculator treats the cycle as not yet
            // begun and every prediction (and the calendar itself) falls back
            // to "no cycle set up". Trimming a period that starts today has
            // no valid later start to move to, so refuse rather than corrupt.
            guard calendar.startOfDay(for: newStart) <= calendar.startOfDay(for: .now) else {
                appState.toast = "Can't move a period start into the future"
                return
            }
            let oldStart = calendar.startOfDay(for: period.startDate)
            period.startDate = calendar.startOfDay(for: newStart)
            if let cycle = calendarCycleRecords.first(where: { $0.id == period.cycleRecordID || calendar.isDate($0.startDate, inSameDayAs: oldStart) }) {
                cycle.startDate = period.startDate
                if cycle.ovulationSource == nil,
                   let baseline = FertilityWindowCalculator.window(for: cycle.startDate, lastPeriodStart: cycle.startDate, averageCycleLength: cycle.averageCycleLengthAtStart, lutealPhaseLength: cycle.lutealPhaseLengthAtStart) {
                    cycle.predictedOvulationDate = baseline.predictedOvulationDate
                    if cycle.confirmedOvulationDate == nil { cycle.expectedPeriodDate = baseline.nextPeriodDate }
                }
                if settings?.lastPeriodStartDate.map({ calendar.isDate($0, inSameDayAs: oldStart) }) == true {
                    settings?.lastPeriodStartDate = period.startDate
                }
            }
        }
        try? modelContext.save()
        AppAnalytics.log("linecheck_period_day_removed", ["edge": edge == .last ? "last" : "first"])
        appState.toast = edge == .last ? "Period end updated" : "Period start updated"
    }

