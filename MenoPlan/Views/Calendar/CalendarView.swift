    private var columns: [GridItem] { Array(repeating: GridItem(.flexible(), spacing: columnSpacing), count: 7) }

    /// Same reasoning as `InlineCalendarMonthView.dayDiameter` - on a wide grid
    /// the day circle tracks its column width instead of staying a fixed dot,
    /// and compact keeps the phone's 34pt. This sheet is wider than the inline
    /// grid, so it gets a correspondingly larger cap.
    private var dayDiameter: CGFloat {
        guard layout.isRegular, gridWidth > 0 else { return 34 }
        let column = (gridWidth - columnSpacing * 6) / 7
        return min(max(34, column - 8), 62)
    }

    private var dotSize: CGFloat { max(6, dayDiameter * 0.13) }
    private var rowHeight: CGFloat { dayDiameter + dotSize + 6 }

