    /// Maps a real date onto the BBT chart's index-based x-axis by linearly
    /// interpolating between the two logged dates it falls between, so a
    /// biological reference date (ovulation, fertile window) that doesn't
    /// land exactly on a logged morning still positions correctly relative
    /// to the temperatures actually logged around it. Returns nil rather
    /// than extrapolating when the date falls outside the logged range - a
    /// marker with a guessed position off the visible chart would be
    /// misleading rather than merely absent.
    private func chartXPosition(for date: Date, in dates: [Date]) -> Double? {
        guard let first = dates.first, let last = dates.last, date >= first, date <= last else { return nil }
        for index in 0..<(dates.count - 1) {
            let start = dates[index]
            let end = dates[index + 1]
            guard date >= start, date <= end else { continue }
            let span = end.timeIntervalSince(start)
            guard span > 0 else { return Double(index) }
            return Double(index) + date.timeIntervalSince(start) / span
        }
        return Double(dates.count - 1)
    }

